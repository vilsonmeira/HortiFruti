-- HortiFruti PDV: base compartilhada para catálogo e pedidos de clientes
-- Execute no SQL Editor do projeto Supabase. Não contém chaves ou senhas.

create extension if not exists pgcrypto;

create or replace function public.hortifruti_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  legacy_id text unique,
  code text not null default '',
  name text not null,
  price numeric(12, 2) not null check (price >= 0),
  unit text not null default 'un',
  category text not null default 'outros',
  emoji text not null default '🥬',
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create index if not exists products_active_name_idx
  on public.products (active, name);

create table if not exists public.customer_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text,
  customer_phone text,
  note text,
  status text not null default 'novo'
    check (status in ('novo', 'em_preparo', 'pronto', 'entregue', 'cancelado')),
  total numeric(12, 2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists customer_orders_created_idx
  on public.customer_orders (created_at desc);

create table if not exists public.customer_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.customer_orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity numeric(12, 3) not null check (quantity > 0),
  line_total numeric(12, 2) not null check (line_total >= 0)
);

create index if not exists customer_order_items_order_idx
  on public.customer_order_items (order_id);

alter table public.products enable row level security;
alter table public.customer_orders enable row level security;
alter table public.customer_order_items enable row level security;

drop policy if exists "Catálogo ativo visível ao público" on public.products;
create policy "Catálogo ativo visível ao público"
  on public.products for select
  to anon, authenticated
  using (active = true or public.hortifruti_is_admin());

drop policy if exists "Admin gerencia catálogo" on public.products;
create policy "Admin gerencia catálogo"
  on public.products for all
  to authenticated
  using (public.hortifruti_is_admin())
  with check (public.hortifruti_is_admin());

drop policy if exists "Admin consulta pedidos" on public.customer_orders;
create policy "Admin consulta pedidos"
  on public.customer_orders for select
  to authenticated
  using (public.hortifruti_is_admin());

drop policy if exists "Admin atualiza pedidos" on public.customer_orders;
create policy "Admin atualiza pedidos"
  on public.customer_orders for update
  to authenticated
  using (public.hortifruti_is_admin())
  with check (public.hortifruti_is_admin());

drop policy if exists "Admin consulta itens dos pedidos" on public.customer_order_items;
create policy "Admin consulta itens dos pedidos"
  on public.customer_order_items for select
  to authenticated
  using (public.hortifruti_is_admin());

create or replace function public.create_customer_order(
  p_items jsonb,
  p_customer_name text default null,
  p_customer_phone text default null,
  p_note text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity numeric(12, 3);
  v_total numeric(12, 2) := 0;
  v_count integer := 0;
begin
  if jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1
     or jsonb_array_length(p_items) > 100 then
    raise exception 'O pedido deve conter entre 1 e 100 itens.';
  end if;

  if length(coalesce(p_customer_name, '')) > 120
     or length(coalesce(p_customer_phone, '')) > 30
     or length(coalesce(p_note, '')) > 500 then
    raise exception 'Dados do cliente excedem o limite permitido.';
  end if;

  insert into public.customer_orders (customer_name, customer_phone, note)
  values (
    nullif(btrim(p_customer_name), ''),
    nullif(btrim(p_customer_phone), ''),
    nullif(btrim(p_note), '')
  )
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_count := v_count + 1;
    begin
      v_quantity := (v_item ->> 'quantity')::numeric;
    exception when others then
      raise exception 'Quantidade inválida no item %.', v_count;
    end;

    if v_quantity is null or v_quantity <= 0 or v_quantity > 9999 then
      raise exception 'Quantidade inválida no item %.', v_count;
    end if;

    select * into v_product
    from public.products
    where id = (v_item ->> 'product_id')::uuid
      and active = true;

    if not found then
      raise exception 'Um produto do pedido não está disponível.';
    end if;

    v_total := v_total + round(v_product.price * v_quantity, 2);

    insert into public.customer_order_items (
      order_id, product_id, product_name, unit, unit_price, quantity, line_total
    ) values (
      v_order_id, v_product.id, v_product.name, v_product.unit,
      v_product.price, v_quantity, round(v_product.price * v_quantity, 2)
    );
  end loop;

  update public.customer_orders
  set total = v_total, updated_at = now()
  where id = v_order_id;

  return v_order_id;
exception when others then
  if v_order_id is not null then
    delete from public.customer_orders where id = v_order_id;
  end if;
  raise;
end;
$$;

revoke all on function public.create_customer_order(jsonb, text, text, text) from public;
grant execute on function public.create_customer_order(jsonb, text, text, text) to anon, authenticated;
grant execute on function public.hortifruti_is_admin() to anon, authenticated;

